#!/usr/bin/env python3
"""Cut the two Revo2 hands out of Booster's T2_31dof_Revo2Hand.urdf -> revo2_left.urdf / revo2_right.urdf.

Each output URDF has ONE root, <side>_wrist_roll_link, which already exists in the robot's main TF tree
(Booster's own robot_state_publisher, configs/T2/robot.urdf, ends at the wrists). A second
robot_state_publisher fed with the finger joint states then hangs the hand frames under it:
    <side>_base_link, <side>_{thumb_metacarpal,thumb_proximal,thumb_distal}_link,
    <side>_{index,middle,ring,pinky}_{proximal,distal}_link            (moving  -> /tf)
    <side>_*_tip_link, <side>_*_touch_link, <side>_base_link            (fixed   -> /tf_static)
One URDF per hand because a URDF must have a single root.

Kinematics (origins, axes, limits, mimic) are copied unchanged. Inertials are kept. Visual/collision
meshes are dropped by default (TF does not need them); --meshes DIR keeps them as file:// paths so
RViz's RobotModel display can show the hands.

    python3 make_hand_urdf.py <path>/T2_31dof_Revo2Hand.urdf [--out DIR] [--meshes <path>/meshes]

Source: github.com/BoosterRobotics/booster_assets robots/T2/T2_31dof_Revo2Hand (commit 12a97516).
"""
from __future__ import annotations

import argparse
import os
import xml.etree.ElementTree as ET


def hand_urdf(root: ET.Element, side: str, mesh_dir: str | None) -> ET.Element:
    base = f"{side}_wrist_roll_link"
    children: dict[str, list[ET.Element]] = {}
    for j in root.findall("joint"):
        children.setdefault(j.find("parent").get("link"), []).append(j)
    links = {l.get("name"): l for l in root.findall("link")}

    out = ET.Element("robot", {"name": f"revo2_{side}_hand"})
    out.append(ET.Comment(f" generated by make_hand_urdf.py from T2_31dof_Revo2Hand.urdf; root = {base} "))
    ET.SubElement(out, "link", {"name": base})          # already published by the main TF tree

    def copy_link(name: str) -> None:
        src = links[name]
        dst = ET.SubElement(out, "link", {"name": name})
        for c in src:
            if c.tag == "inertial":
                dst.append(c)
            elif c.tag in ("visual", "collision") and mesh_dir:
                m = c.find("geometry/mesh")
                if m is not None:
                    m.set("filename", "file://" + os.path.join(os.path.abspath(mesh_dir),
                                                                os.path.basename(m.get("filename"))))
                dst.append(c)

    stack = [base]
    while stack:
        parent = stack.pop()
        for j in children.get(parent, []):
            child = j.find("child").get("link")
            copy_link(child)
            out.append(j)
            stack.append(child)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("urdf", help="T2_31dof_Revo2Hand.urdf")
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--meshes", default=None, help="keep visual/collision meshes from this folder")
    a = ap.parse_args()
    root = ET.parse(a.urdf).getroot()
    for side in ("left", "right"):
        tree = ET.ElementTree(hand_urdf(root, side, a.meshes))
        ET.indent(tree, space="  ")
        path = os.path.join(a.out, f"revo2_{side}.urdf")
        tree.write(path, encoding="utf-8", xml_declaration=True)
        n_rev = sum(1 for j in tree.getroot().findall("joint") if j.get("type") == "revolute")
        n_fix = sum(1 for j in tree.getroot().findall("joint") if j.get("type") == "fixed")
        print(f"wrote {path}: {n_rev} revolute + {n_fix} fixed joints")


if __name__ == "__main__":
    main()
